function makeApproaches(
  brute: { title: string; time: string; space: string; insight: string; ts: string; py: string; java: string },
  better: { title: string; time: string; space: string; insight: string; ts: string; py: string; java: string },
  optimal: { title: string; time: string; space: string; insight: string; ts: string; py: string; java: string },
): [TierApproach, TierApproach, TierApproach] {
  return [
    {
      tier: 'Brute Force',
      title: brute.title,
      timeComplexity: brute.time,
      spaceComplexity: brute.space,
      keyInsight: brute.insight,
      code: { typescript: brute.ts, python: brute.py, java: brute.java },
    },
    {
      tier: 'Better',
      title: better.title,
      timeComplexity: better.time,
      spaceComplexity: better.space,
      keyInsight: better.insight,
      code: { typescript: better.ts, python: better.py, java: better.java },
    },
    {
      tier: 'Optimal',
      title: optimal.title,
      timeComplexity: optimal.time,
      spaceComplexity: optimal.space,
      keyInsight: optimal.insight,
      code: { typescript: optimal.ts, python: optimal.py, java: optimal.java },
    },
  ];
}

function defaultSocratic(
  deconstruct: string,
  hypothesize: string,
  build: string,
  verify: string,
): Record<SocraticPhase, string> {
  return {
    DECONSTRUCT: deconstruct,
    HYPOTHESIZE: hypothesize,
    ELIMINATE_OR_BUILD: build,
    VERIFY_EDGE_CASES: verify,
  };
}

