function makePayloads(
  component: string,
  successBody: Record<string, unknown>,
  degradedBody: Record<string, unknown>,
  errorCode: number,
  errorText: string,
  errorBody: Record<string, unknown>,
  extraSuccessHeaders: Record<string, string> = {},
): MockPayloads {
  return {
    successResponse: {
      statusCode: 200,
      statusText: 'OK',
      headers: {
        'content-type': 'application/json',
        'x-handled-by': component,
        'x-trace-id': 'trc_9f82a41c7b',
        ...extraSuccessHeaders,
      },
      body: successBody,
    },
    degradedResponse: {
      statusCode: 200,
      statusText: 'OK (Degraded Latency)',
      headers: {
        'content-type': 'application/json',
        'x-handled-by': component,
        'x-health-warning': 'elevated-p99-latency',
      },
      body: degradedBody,
    },
    errorResponse: {
      statusCode: errorCode,
      statusText: errorText,
      headers: {
        'content-type': 'application/json',
        'x-failed-node': component,
        'retry-after': '5',
      },
      body: errorBody,
    },
  };
}

